const phoneCount = {};
for (const s of SHEMESH_SITE) {
  const np = normalizePhone(s.phone);
  phoneCount[np] = (phoneCount[np] || 0) + 1;
}
for (const s of SHEMESH_SITE) {
  const np = normalizePhone(s.phone);
  if (phoneCount[np] === 1) {
    SHEMESH_BY_PHONE[np] = s;
  } else {
    if (!SHEMESH_COLLISION_BY_ADDR[np]) SHEMESH_COLLISION_BY_ADDR[np] = [];
    SHEMESH_COLLISION_BY_ADDR[np].push(s);
  }
}

function lookupShemesh(place) {
  const np = normalizePhone(place.phone);
  if (SHEMESH_BY_PHONE[np]) return SHEMESH_BY_PHONE[np];
  if (SHEMESH_COLLISION_BY_ADDR[np]) {
    const addr = (place.address || '').replace(/,.*/, '').trim();
    for (const s of SHEMESH_COLLISION_BY_ADDR[np]) {
      if (addr.includes(s.address.split(' ')[0]) || s.address.includes(addr.split(' ')[0])) return s;
    }
    return SHEMESH_COLLISION_BY_ADDR[np][0];
  }
  return null;
}

