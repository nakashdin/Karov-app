function normalizePhone(p) {
  if (!p) return '';
  return p.replace(/[-\s\(\)\.×–]/g, '').replace(/^\+972/, '0').replace(/^972/, '0');
}

function mapKosherType(text) {
  if (!text) return null;
  const t = text;
  if (t.includes('בד"צ בית יוסף') || t.includes('בד"ץ בית יוסף') || t.includes('בית יוסף')) return 'badatz_beit_yosef';
  if (t.includes('העדה החרדית') || t.includes('בד"צ העדה החרדית') || t.includes('בד"ץ העדה החרדית') || t.includes('בית ישראל')) return 'badatz_edah';
  if (t.includes('לנדא') || t.includes('לנדאו')) return 'rabanut_mehadrin';
  if (t.includes('רובין')) return 'rabanut_mehadrin';
  if (t.includes('רבני הקריות')) return 'rabanut_mehadrin';
  if (t.includes('רבנות מקומית')) return 'rabanut_mekomi';
  if (t.includes('רבונות מקומית מהדרין')) return 'rabanut_mehadrin';
  if (t.includes('רבנות ובד"ץ') || t.includes('רבנות ובד"צ')) return 'mehadrin';
  if (t.includes('מהדרין')) return 'mehadrin';
  if (t.includes('בד"ץ') || t.includes('בד"צ')) return 'mehadrin';
  if (t.includes('רבנות')) return 'rabanut';
  return 'kosher';
}

// Parse Pizza Hut hours: format is "CLOSE-OPEN" per day
function parseHutHours(hoursStr) {
  if (!hoursStr || hoursStr === 'סגור כל השבוע' || hoursStr === 'סגור') return null;
  const dayMap = {
    'יום ראשון': 'Su', 'יום שני': 'M', 'יום שלישי': 'Tu',
    'יום רביעי': 'W', 'יום חמישי': 'Th', 'יום שישי': 'Fr', 'יום שבת': 'Sa'
  };
  const parts = hoursStr.split(' | ');
  const dayHours = {};
  for (const part of parts) {
    const m = part.match(/^(יום \S+): (.+)$/);
    if (!m) continue;
    const [, dayHe, times] = m;
    const dayEn = dayMap[dayHe];
    if (!dayEn) continue;
    if (times === 'סגור') { dayHours[dayEn] = 'off'; continue; }
    const [close, open] = times.split('-');
    if (open && close) dayHours[dayEn] = `${open}-${close}`;
  }
  const dayOrder = ['Su', 'M', 'Tu', 'W', 'Th', 'Fr', 'Sa'];
  const segments = [];
  let i = 0;
  while (i < dayOrder.length) {
    const day = dayOrder[i];
    const h = dayHours[day];
    if (!h || h === 'off') { i++; continue; }
    let j = i;
    while (j + 1 < dayOrder.length && dayHours[dayOrder[j + 1]] === h) j++;
    const label = i === j ? day : `${dayOrder[i]}-${dayOrder[j]}`;
    segments.push(`${label} ${h}`);
    i = j + 1;
  }
  return segments.length ? segments.join('; ') : null;
}

