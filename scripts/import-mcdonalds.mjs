// שעות: מוסיף Mo = Tu (ווידא שהשעות זהות דרך הדפדפן)
function addMonday(hours) {
  if (!hours) return hours;
  const tuMatch = hours.match(/Tu (\d{2}:\d{2}-\d{2}:\d{2})/);
  if (tuMatch) return `Mo ${tuMatch[1]}; ${hours}`;
  return hours;
}

