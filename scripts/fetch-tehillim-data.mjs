/**
 * One-time script: fetches all 150 chapters of Tehillim from Sefaria (public domain Masoretic text)
 * and writes them as a local TypeScript data file so the app never calls Sefaria at runtime.
 *
 * Usage:  node scripts/fetch-tehillim-data.mjs
 *
 * Output: src/data/tehillimText.ts
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'data', 'tehillimText.ts');

const TOTAL = 150;
const DELAY_MS = 350; // polite rate-limit

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function stripTags(str) {
  return str.replace(/<[^>]+>/g, '').trim();
}

console.log(`\nFetching ${TOTAL} chapters from Sefaria …\n`);

const chapters = [];

for (let i = 1; i <= TOTAL; i++) {
  process.stdout.write(`  פרק ${i}/${TOTAL} … `);
  try {
    const res = await fetch(
      `https://www.sefaria.org/api/texts/Psalms.${i}?lang=he&context=0`,
    );
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    const verses = (json.he ?? []).map(stripTags).filter(Boolean);
    chapters.push({ num: i, verses });
    console.log(`✓  (${verses.length} פסוקים)`);
  } catch (err) {
    console.log(`✗  שגיאה: ${err.message}`);
    chapters.push({ num: i, verses: [] });
  }
  if (i < TOTAL) await sleep(DELAY_MS);
}

const header = `// Auto-generated by scripts/fetch-tehillim-data.mjs
// Source: Sefaria.org — Masoretic text (public domain)
// Run "node scripts/fetch-tehillim-data.mjs" to regenerate.
// DO NOT edit manually.

export interface TehillimChapterText {
  num: number;
  verses: string[];
}

export const TEHILLIM_TEXT: TehillimChapterText[] = `;

const body = JSON.stringify(chapters, null, 2);
const footer = `;\n`;

writeFileSync(OUT, header + body + footer, 'utf8');

const filled = chapters.filter((c) => c.verses.length > 0).length;
console.log(`\n✅  נכתב: src/data/tehillimText.ts`);
console.log(`   פרקים עם טקסט: ${filled}/${TOTAL}\n`);
