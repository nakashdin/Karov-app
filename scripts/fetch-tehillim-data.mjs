/**
 * One-time script: fetches all 150 chapters of Tehillim from Sefaria (public domain Masoretic text)
 * and writes them as a local TypeScript data file so the app never calls Sefaria at runtime.
 *
 * Usage:  node scripts/fetch-tehillim-data.mjs
 * Output: src/data/tehillimText.ts
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'data', 'tehillimText.ts');

const TOTAL = 150;
const DELAY_MS = 350;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Cantillation marks (trope) via explicit Unicode code points:
//   ֑-֯ : Hebrew accent marks (etnahta .. judeo-spanish varika)
//   ׀        : PASEQ (the | pipe character)
//   ׃-׆ : SOF PASUQ and related
// Nikud (vowels) ְ-ׂ are intentionally KEPT.
const CANTILLATION_RE = /[֑-֯׀׃-׆]/g;

function cleanVerse(str) {
  return str
    .replace(/<[^>]+>/g, '')
    .replace(/&thinsp;/g, '')
    .replace(/ /g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\{.\}/g, '')
    .replace(CANTILLATION_RE, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

console.log('\nFetching ' + TOTAL + ' chapters from Sefaria ...\n');

const chapters = [];

for (let i = 1; i <= TOTAL; i++) {
  process.stdout.write('  ' + i + '/' + TOTAL + ' ... ');
  try {
    const res = await fetch(
      'https://www.sefaria.org/api/texts/Psalms.' + i + '?lang=he&context=0',
    );
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const json = await res.json();
    const verses = (json.he ?? []).map(cleanVerse).filter(Boolean);
    chapters.push({ num: i, verses });
    console.log('OK (' + verses.length + ' verses)');
  } catch (err) {
    console.log('ERROR: ' + err.message);
    chapters.push({ num: i, verses: [] });
  }
  if (i < TOTAL) await sleep(DELAY_MS);
}

const tsHeader =
  '// Auto-generated by scripts/fetch-tehillim-data.mjs\n' +
  '// Source: Sefaria.org -- Masoretic text (public domain)\n' +
  '// Run "node scripts/fetch-tehillim-data.mjs" to regenerate.\n' +
  '// DO NOT edit manually.\n\n' +
  'export interface TehillimChapterText {\n' +
  '  num: number;\n' +
  '  verses: string[];\n' +
  '}\n\n' +
  'export const TEHILLIM_TEXT: TehillimChapterText[] = ';

writeFileSync(OUT, tsHeader + JSON.stringify(chapters, null, 2) + ';\n', 'utf8');

const filled = chapters.filter((c) => c.verses.length > 0).length;
console.log('\nDone -> src/data/tehillimText.ts');
console.log('Chapters with text: ' + filled + '/' + TOTAL + '\n');
