const VALID_TYPES: ContentType[] = ['halacha', 'mussar', 'thought', 'blessing'];

function getDayOfYear(): number {
  const d = new Date();
  const start = new Date(d.getFullYear(), 0, 0);
  return Math.floor((d.getTime() - start.getTime()) / 86_400_000);
}

export function useDailyContent(): DailyContent {
  const [type, setTypeState] = useState<ContentType>('halacha');

  useEffect(() => {
    AsyncStorage.getItem(PREF_KEY).then((stored) => {
      if (stored && (VALID_TYPES as string[]).includes(stored)) {
        setTypeState(stored as ContentType);
      }
    }).catch(() => {});
  }, []);

  const dayOfYear = getDayOfYear();
  const items = CONTENT[type];
  const item = items[dayOfYear % items.length];

  const setType = (t: ContentType) => {
    setTypeState(t);
    AsyncStorage.setItem(PREF_KEY, t).catch(() => {});
  };

  return { type, typeName: TYPE_NAMES[type], item, setType };
}
